// Helper function to search Hargeisa places and businesses
export function searchHargeisaPlaces(query: string, categoryFilter?: string): HargeisaPlace[] {
  if (!query || query.trim() === '') {
    if (categoryFilter && categoryFilter !== 'All') {
      return HARGEISA_PLACES.filter((p) => p.category.toLowerCase().includes(categoryFilter.toLowerCase()));
    }
    return HARGEISA_PLACES.filter((p) => p.popular);
  }

  const cleanQuery = query.toLowerCase().trim();
  const queryWords = cleanQuery.split(/\s+/).filter(Boolean);

  return HARGEISA_PLACES.filter((place) => {
    if (categoryFilter && categoryFilter !== 'All') {
      if (!place.category.toLowerCase().includes(categoryFilter.toLowerCase())) {
        return false;
      }
    }

    const nameMatch = place.name.toLowerCase().includes(cleanQuery);
    const addressMatch = place.address.toLowerCase().includes(cleanQuery);
    const categoryMatch = place.category.toLowerCase().includes(cleanQuery);
    const districtMatch = place.district ? place.district.toLowerCase().includes(cleanQuery) : false;
    const subCategoryMatch = place.subCategory ? place.subCategory.toLowerCase().includes(cleanQuery) : false;

    // Check search terms
    const termMatch = place.searchTerms.some((term) =>
      term.includes(cleanQuery) || cleanQuery.includes(term)
    );

    // Multi-word check: all words must match somewhere
    const allWordsMatch = queryWords.every((word) =>
      place.name.toLowerCase().includes(word) ||
      place.address.toLowerCase().includes(word) ||
      place.searchTerms.some((t) => t.includes(word)) ||
      (place.district && place.district.toLowerCase().includes(word))
    );

    return nameMatch || addressMatch || categoryMatch || districtMatch || subCategoryMatch || termMatch || allWordsMatch;
  });
}
